-- Real worker accounts that use a password before phone ownership is verified.
-- The app can manage the account/profile, while phone-sharing and other verified
-- worker flows remain behind the existing OTP verification gate.

create table if not exists public.candidate_password_auth_attempts (
  id bigint generated by default as identity primary key,
  phone_hash text not null,
  ip_hash text not null,
  created_at timestamptz not null default now()
);

create index if not exists candidate_password_auth_phone_created_idx
  on public.candidate_password_auth_attempts(phone_hash, created_at desc);
create index if not exists candidate_password_auth_ip_created_idx
  on public.candidate_password_auth_attempts(ip_hash, created_at desc);

alter table public.candidate_password_auth_attempts enable row level security;

create or replace function public.consume_candidate_password_auth_attempt(
  p_phone_hash text,
  p_ip_hash text
) returns boolean
language plpgsql security definer set search_path = public
as $$
begin
  if p_phone_hash !~ '^[0-9a-f]{64}$' or p_ip_hash !~ '^[0-9a-f]{64}$' then
    return false;
  end if;

  perform pg_advisory_xact_lock(hashtextextended('candidate-password-phone:' || p_phone_hash, 0));
  perform pg_advisory_xact_lock(hashtextextended('candidate-password-ip:' || p_ip_hash, 0));

  delete from public.candidate_password_auth_attempts
    where created_at < now() - interval '24 hours';

  if (select count(*) from public.candidate_password_auth_attempts
      where phone_hash = p_phone_hash and created_at > now() - interval '15 minutes') >= 10
     or (select count(*) from public.candidate_password_auth_attempts
      where ip_hash = p_ip_hash and created_at > now() - interval '1 hour') >= 60 then
    return false;
  end if;

  insert into public.candidate_password_auth_attempts(phone_hash, ip_hash)
    values (p_phone_hash, p_ip_hash);
  return true;
end;
$$;

revoke all on function public.consume_candidate_password_auth_attempt(text, text) from public, anon, authenticated;
grant execute on function public.consume_candidate_password_auth_attempt(text, text) to service_role;

create or replace function public.register_candidate_password_account(
  p_phone text,
  p_full_name text,
  p_password_hash text
) returns table (created boolean, user_id uuid, full_name text)
language plpgsql security definer set search_path = public
as $$
declare
  v_user_id uuid;
  v_full_name text := btrim(p_full_name);
begin
  if p_phone is null or p_phone !~ '^0[0-9]{9}$'
     or v_full_name is null or length(v_full_name) < 2 or length(v_full_name) > 100
     or p_password_hash is null or p_password_hash not like '$2%' then
    return query select false, null::uuid, null::text;
    return;
  end if;

  perform pg_advisory_xact_lock(hashtextextended('candidate-password-register:' || p_phone, 0));

  -- Never claim an OTP account, another role, or an existing guest application/profile
  -- based only on a phone number supplied by an unverified registrant.
  if exists (
    select 1 from public.users u
    where public.normalize_vn_phone(u.phone) = p_phone
  ) or exists (
    select 1 from public.candidates c
    where public.normalize_vn_phone(c.phone) = p_phone
  ) then
    return query select false, null::uuid, null::text;
    return;
  end if;

  insert into public.users(phone, password_hash, full_name, role, is_verified, status)
    values (p_phone, p_password_hash, v_full_name, 'candidate', false, 'active')
    returning id into v_user_id;

  insert into public.candidates(full_name, phone, status, source, user_id)
    values (v_full_name, p_phone, 'new', 'worker_password_signup', v_user_id);

  return query select true, v_user_id, v_full_name;
exception when unique_violation then
  -- Covers collisions with the exact unique phone index if another writer bypasses
  -- this endpoint's normalized-phone advisory lock.
  return query select false, null::uuid, null::text;
end;
$$;

revoke all on function public.register_candidate_password_account(text, text, text) from public, anon, authenticated;
grant execute on function public.register_candidate_password_account(text, text, text) to service_role;
